export function getQualificationPackByCode(code: string): QualificationPack | undefined {
  return QUALIFICATION_PACKS.find((qp) => qp.code.toLowerCase() === code.toLowerCase());
}

export function recommendQualificationPacks(
  sector: string,
  declaredSkills: string[],
  experienceMonths: number
): QualificationPack[] {
  return QUALIFICATION_PACKS.filter((qp) => {
    // Sector affinity or skill overlap
    const sectorMatch = qp.sector.toLowerCase().includes(sector.toLowerCase()) || sector.toLowerCase().includes(qp.sector.toLowerCase());
    const skillMatch = qp.coreCompetencies.some((c) =>
      declaredSkills.some((s) => c.title.toLowerCase().includes(s.toLowerCase()) || c.description.toLowerCase().includes(s.toLowerCase()))
    );
    const hasMinExperience = experienceMonths >= Math.floor(qp.minimumExperienceMonths * 0.7); // Allow nearby experience
    return (sectorMatch || skillMatch) && hasMinExperience;
  });
}
